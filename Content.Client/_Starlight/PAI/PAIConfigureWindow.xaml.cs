using Content.Client.UserInterface.Controls;
using Content.Shared.CCVar;
using Content.Shared.NameIdentifier;
using Content.Shared.NameModifier.EntitySystems;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.PAI;

[GenerateTypedNameReferences]
public sealed partial class PAIConfigureWindow : FancyWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _protoManager = default!;
    [Dependency] private IConfigurationManager _cfgManager = default!;

    private readonly NameModifierSystem _nameModifier;

    public Action<string>? RenameButtonPressed;
    private string _lastValidName;

    private readonly int _maxNameLength;
    private EntityUid _entity;
    public PAIConfigureWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _nameModifier = _entManager.System<NameModifierSystem>();

        PAIConfigureTabs.SetTabTitle(0, Loc.GetString("pai-system-configure-customize"));
        PAIConfigureTabs.SetTabTitle(1, Loc.GetString("pai-system-configure-memory"));

        _maxNameLength = _cfgManager.GetCVar(CCVars.MaxNameLength);
        _lastValidName = RenameLineEdit.Text;
        RenameButton.OnPressed += _ => RenameButtonPressed?.Invoke(_lastValidName);
        RenameButton.OnPressed += _ => PAIName.Text = _lastValidName;

        RenameLineEdit.OnTextChanged += OnNameChanged;
    }

    public void SetEntity(EntityUid entity)
    {
        _entity = entity;
        DeviceSprite.SetEntity(entity);

        if (_entManager.TryGetComponent<NameIdentifierComponent>(_entity, out var nameIdentifierComponent))
        {
            PAIName.Visible = true;
            PAIName.Text = nameIdentifierComponent.FullIdentifier;

            RenameLineEdit.Text = _nameModifier.GetBaseName(entity);
        }
        else
        {
            PAIName.Text = _entManager.GetComponent<MetaDataComponent>(_entity).EntityName;
            RenameLineEdit.Text = _entManager.GetComponent<MetaDataComponent>(_entity).EntityName;
        }
    }

    private void OnNameChanged(LineEdit.LineEditEventArgs obj)
    {
        if (obj.Text.Length == 0 ||
            string.IsNullOrWhiteSpace(obj.Text) ||
            string.IsNullOrEmpty(obj.Text))
            return;

        if (obj.Text.Length > _maxNameLength)
            obj.Control.Text = obj.Text[.._maxNameLength];

        _lastValidName = obj.Control.Text;
        obj.Control.Text = _lastValidName;
    }
}

