namespace Content.Client._Starlight.PAI;

[GenerateTypedNameReferences]
public sealed partial class PAIConfigureVoicePopup : FancyWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _protoManager = default!;
    private readonly TextToSpeechSystem _tts;


    public Action<VoicePrototype>? SelectedVoice;

    private List<VoicePrototype> _siliconVoices = [];
    private VoicePicker _siliconVoicePicker = default!;

    public PAIConfigureVoicePopup()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _tts = _entManager.System<TextToSpeechSystem>();

        _siliconVoices =
        [
            .. _protoManager
            .EnumeratePrototypes<VoicePrototype>()
            .Where(voice => voice.Silicon)
        ];
        _siliconVoicePicker = new VoicePicker(_siliconVoices, _protoManager) { Visible = true };
        _siliconVoicePicker.OnVoiceSelected += voice => SelectedVoice?.Invoke(voice);
        _siliconVoicePicker.OnPreviewRequested += voice => _tts.RequestPreviewTts(voice.ID);

        // none of the silicon voices have pitch tags, currently
        List<SegmentedButtons> filter = _siliconVoicePicker.GetControlOfType<SegmentedButtons>();
        filter.Last().Visible = false;

        VoicePickerSlot.AddChild(_siliconVoicePicker);
    }

    public void SelectHighlightedVoice(VoicePrototype voice)
    {
        _siliconVoicePicker.Select(voice.ID);
    }
}

